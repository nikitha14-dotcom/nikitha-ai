import os
import uuid
from pathlib import Path
from typing import List, Dict, Any
from backend.app.config import settings

class DocumentGenerator:
    @staticmethod
    def generate_pdf(title: str, topic: str, sections: List[Dict[str, Any]], author: str = "NIKITHA.AI") -> str:
        """Generates a professional PDF report using ReportLab"""
        from reportlab.lib.pagesizes import letter
        from reportlab.lib import colors
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable, Table, TableStyle

        filename = f"{topic.lower().replace(' ', '_')[:25]}_{uuid.uuid4().hex[:6]}.pdf"
        filepath = settings.DOCS_PATH / filename

        doc = SimpleDocTemplate(
            str(filepath),
            pagesize=letter,
            rightMargin=54,
            leftMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            'DocTitle',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=22,
            leading=26,
            textColor=colors.HexColor('#1e1b4b'),
            spaceAfter=6
        )
        subtitle_style = ParagraphStyle(
            'DocSubtitle',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=11,
            leading=14,
            textColor=colors.HexColor('#6b7280'),
            spaceAfter=15
        )
        h2_style = ParagraphStyle(
            'DocH2',
            parent=styles['Heading2'],
            fontName='Helvetica-Bold',
            fontSize=14,
            leading=18,
            textColor=colors.HexColor('#4338ca'),
            spaceBefore=12,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            'DocBody',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=10,
            leading=15,
            textColor=colors.HexColor('#1f2937'),
            spaceAfter=8
        )

        story = []
        story.append(Paragraph(title, title_style))
        story.append(Paragraph(f"Generated by {author} • Topic: {topic}", subtitle_style))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#6366f1'), spaceAfter=15))

        for section in sections:
            sec_title = section.get("title", "")
            sec_content = section.get("content", "")
            if sec_title:
                story.append(Paragraph(sec_title, h2_style))
            if sec_content:
                paragraphs = sec_content.split("\n")
                for p in paragraphs:
                    if p.strip():
                        story.append(Paragraph(p.strip(), body_style))
            story.append(Spacer(1, 8))

        doc.build(story)
        return filename

    @staticmethod
    def generate_docx(title: str, topic: str, sections: List[Dict[str, Any]], author: str = "NIKITHA.AI") -> str:
        """Generates a professional Word .docx document using python-docx"""
        from docx import Document
        from docx.shared import Inches, Pt, RGBColor
        from docx.enum.text import WD_ALIGN_PARAGRAPH

        doc = Document()
        
        # Title
        p_title = doc.add_paragraph()
        run_title = p_title.add_run(title)
        run_title.font.name = 'Arial'
        run_title.font.size = Pt(22)
        run_title.font.bold = True
        run_title.font.color.rgb = RGBColor(30, 27, 75)
        p_title.alignment = WD_ALIGN_PARAGRAPH.LEFT

        # Subtitle
        p_sub = doc.add_paragraph()
        run_sub = p_sub.add_run(f"Authored by {author} | Topic: {topic}")
        run_sub.font.name = 'Arial'
        run_sub.font.size = Pt(10)
        run_sub.font.color.rgb = RGBColor(107, 114, 128)

        doc.add_paragraph().add_run("―" * 45).font.color.rgb = RGBColor(99, 102, 241)

        for sec in sections:
            sec_title = sec.get("title", "")
            sec_content = sec.get("content", "")
            if sec_title:
                h = doc.add_heading(sec_title, level=2)
                h.style.font.name = 'Arial'
                h.style.font.color.rgb = RGBColor(67, 56, 202)
            if sec_content:
                for line in sec_content.split("\n"):
                    if line.strip():
                        p = doc.add_paragraph(line.strip())
                        p.style.font.name = 'Arial'
                        p.style.font.size = Pt(10.5)

        filename = f"{topic.lower().replace(' ', '_')[:25]}_{uuid.uuid4().hex[:6]}.docx"
        filepath = settings.DOCS_PATH / filename
        doc.save(str(filepath))
        return filename

    @staticmethod
    def generate_xlsx(title: str, topic: str, rows: List[List[Any]], headers: List[str]) -> str:
        """Generates a styled Excel .xlsx spreadsheet using openpyxl"""
        import openpyxl
        from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = topic[:30] if topic else "Sheet1"

        # Title row
        ws.merge_cells("A1:E1")
        title_cell = ws["A1"]
        title_cell.value = f"{title} - {topic}"
        title_cell.font = Font(name="Calibri", size=15, bold=True, color="FFFFFF")
        title_cell.fill = PatternFill(start_color="312E81", end_color="312E81", fill_type="solid")
        title_cell.alignment = Alignment(horizontal="center", vertical="center")
        ws.row_dimensions[1].height = 32

        # Header row
        header_fill = PatternFill(start_color="4F46E5", end_color="4F46E5", fill_type="solid")
        header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
        for col_idx, header in enumerate(headers, 1):
            cell = ws.cell(row=3, column=col_idx, value=header)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(horizontal="left", vertical="center")
        ws.row_dimensions[3].height = 24

        # Data rows
        thin_border = Border(
            left=Side(style='thin', color='E5E7EB'),
            right=Side(style='thin', color='E5E7EB'),
            top=Side(style='thin', color='E5E7EB'),
            bottom=Side(style='thin', color='E5E7EB')
        )
        for r_idx, row_data in enumerate(rows, 4):
            bg_color = "F9FAFB" if r_idx % 2 == 0 else "FFFFFF"
            row_fill = PatternFill(start_color=bg_color, end_color=bg_color, fill_type="solid")
            for c_idx, val in enumerate(row_data, 1):
                cell = ws.cell(row=r_idx, column=c_idx, value=val)
                cell.fill = row_fill
                cell.border = thin_border
                cell.font = Font(name="Calibri", size=10)

        # Auto column widths
        for col in ws.columns:
            max_len = max(len(str(cell.value or '')) for cell in col)
            col_letter = openpyxl.utils.get_column_letter(col[0].column)
            ws.column_dimensions[col_letter].width = max(max_len + 4, 14)

        filename = f"{topic.lower().replace(' ', '_')[:25]}_{uuid.uuid4().hex[:6]}.xlsx"
        filepath = settings.DOCS_PATH / filename
        wb.save(str(filepath))
        return filename
